package java_basic;

public class HarmonicSerise {
	public static void main(String[] args) {
		
		for(float i = 1; i <= 10;i++) {
			System.out.print(1/i + ",");
		}
		System.out.println();
		System.out.println("------------------");
		for(int i = 1;i <= 10;i++) {
			System.out.print("1/" + i + " + ");
		}
    }
}
